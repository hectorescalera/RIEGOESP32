-- Cola temporal de ordenes para un prototipo de un solo ESP32.
create table if not exists public.ordenes_riego (
  id bigint generated by default as identity primary key,
  accion text not null default 'regar'
    check (accion = 'regar'),
  duracion_seg integer not null
    check (duracion_seg between 5 and 60),
  volumen_ml integer not null
    check (volumen_ml between 50 and 2000),
  dispositivo text not null default 'ESP32_RIEGO_01',
  estado text not null default 'pendiente'
    check (estado in ('pendiente', 'procesando', 'completada', 'fallida', 'expirada')),
  error text,
  creada_en timestamptz not null default pg_catalog.now(),
  vence_en timestamptz not null default (pg_catalog.now() + interval '2 minutes'),
  iniciada_en timestamptz,
  finalizada_en timestamptz,
  check (finalizada_en is null or iniciada_en is null or finalizada_en >= iniciada_en)
);

create index if not exists ordenes_riego_pendientes_idx
on public.ordenes_riego (dispositivo, estado, id);

alter table public.ordenes_riego enable row level security;

drop policy if exists ordenes_riego_select on public.ordenes_riego;
create policy ordenes_riego_select
on public.ordenes_riego
for select
to anon, authenticated
using (true);

drop policy if exists ordenes_riego_insert on public.ordenes_riego;
create policy ordenes_riego_insert
on public.ordenes_riego
for insert
to anon, authenticated
with check (
  estado = 'pendiente'
  and accion = 'regar'
  and vence_en > pg_catalog.now()
  and vence_en <= pg_catalog.now() + interval '2 minutes'
);

drop policy if exists ordenes_riego_update on public.ordenes_riego;
create policy ordenes_riego_update
on public.ordenes_riego
for update
to anon, authenticated
using (estado in ('pendiente', 'procesando'))
with check (estado in ('procesando', 'completada', 'fallida', 'expirada'));

grant usage on schema public to anon, authenticated;
grant select, insert, update on public.ordenes_riego to anon, authenticated;
grant usage, select on sequence public.ordenes_riego_id_seq to anon, authenticated;

create or replace function public.tomar_orden_riego()
returns setof public.ordenes_riego
language plpgsql
set search_path = ''
as $$
declare
  orden public.ordenes_riego%rowtype;
begin
  update public.ordenes_riego
  set estado = 'fallida',
      finalizada_en = pg_catalog.now(),
      error = 'El ESP32 dejo de reportar mientras ejecutaba la orden.'
  where estado = 'procesando'
    and iniciada_en <= pg_catalog.now() - interval '3 minutes';

  update public.ordenes_riego
  set estado = 'expirada',
      finalizada_en = pg_catalog.now(),
      error = 'La orden vencio antes de ser procesada.'
  where estado = 'pendiente'
    and vence_en <= pg_catalog.now();

  select *
  into orden
  from public.ordenes_riego
  where dispositivo = 'ESP32_RIEGO_01'
    and estado = 'pendiente'
    and vence_en > pg_catalog.now()
  order by id
  limit 1
  for update skip locked;

  if not found then
    return;
  end if;

  update public.ordenes_riego
  set estado = 'procesando',
      iniciada_en = pg_catalog.now()
  where id = orden.id
  returning * into orden;

  return next orden;
end;
$$;

grant execute on function public.tomar_orden_riego() to anon, authenticated;

create or replace function public.marcar_finalizacion_orden_riego()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.estado in ('completada', 'fallida', 'expirada')
     and old.estado not in ('completada', 'fallida', 'expirada') then
    new.finalizada_en = pg_catalog.now();
  end if;

  return new;
end;
$$;

drop trigger if exists ordenes_riego_finalizada_en
on public.ordenes_riego;

create trigger ordenes_riego_finalizada_en
before update on public.ordenes_riego
for each row
execute function public.marcar_finalizacion_orden_riego();
